CREATE TABLE IF NOT EXISTS companies (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(160) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS contacts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 company_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(160) NOT NULL,
 phone VARCHAR(20) NOT NULL,
 opted_in BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_contact_company_phone(company_id,phone),
 CONSTRAINT fk_contact_company FOREIGN KEY(company_id) REFERENCES companies(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS campaigns (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 company_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(160) NOT NULL,
 template_name VARCHAR(160) NOT NULL,
 status ENUM('DRAFT','QUEUED','PROCESSING','COMPLETED','CANCELLED') NOT NULL DEFAULT 'DRAFT',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_campaign_company FOREIGN KEY(company_id) REFERENCES companies(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 campaign_id BIGINT UNSIGNED NOT NULL,
 contact_id BIGINT UNSIGNED NOT NULL,
 status ENUM('PENDING','QUEUED','SENT','DELIVERED','READ','FAILED') NOT NULL DEFAULT 'PENDING',
 provider_message_id VARCHAR(255) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_campaign_contact(campaign_id,contact_id),
 CONSTRAINT fk_message_campaign FOREIGN KEY(campaign_id) REFERENCES campaigns(id),
 CONSTRAINT fk_message_contact FOREIGN KEY(contact_id) REFERENCES contacts(id)
) ENGINE=InnoDB;
